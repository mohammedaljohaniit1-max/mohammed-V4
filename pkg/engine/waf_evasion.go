// FingerprintWAF classifies a response into a WAF/CDN verdict from its status,
// headers and (already lower-cased) body sample. It scans headers first (most
// authoritative) then body signals, and finally treats a bare 403/406/429 with
// no other explanation as a generic WAF challenge.
func FingerprintWAF(status int, headers http.Header, lowerBody string) WAFFingerprint {
	fp := WAFFingerprint{}

	for _, s := range wafHeaderSignals {
		v := headers.Get(s.header)
		if v == "" {
			// Set-Cookie may repeat; join all values for substring search.
			if strings.EqualFold(s.header, "Set-Cookie") {
				v = strings.Join(headers.Values("Set-Cookie"), "; ")
			}
			if v == "" {
				continue
			}
		}
		if s.valueSub == "" || strings.Contains(strings.ToLower(v), s.valueSub) {
			fp.Detected = true
			if fp.Vendor == WAFNone {
				fp.Vendor = s.vendor
			}
			if s.isChalenge {
				fp.Challenge = true
			}
			fp.Signals = append(fp.Signals, string(s.vendor)+" header "+s.header)
		}
	}

	for _, s := range wafBodySignals {
		if strings.Contains(lowerBody, s.sub) {
			fp.Detected = true
			if fp.Vendor == WAFNone || fp.Vendor == WAFGeneric {
				fp.Vendor = s.vendor
			}
			if s.isChalenge {
				fp.Challenge = true
			}
			fp.Signals = append(fp.Signals, string(s.vendor)+` body "`+s.sub+`"`)
		}
	}

	// A 403/406/429 with no positive vendor evidence is still very likely a WAF
	// interstitial — treat it as a generic challenge so heavy fuzzing is skipped.
	if !fp.Detected && (status == 403 || status == 406 || status == 429) {
		fp.Detected = true
		fp.Vendor = WAFGeneric
		fp.Challenge = true
		fp.Signals = append(fp.Signals, "bare block status")
	}

	return fp
}

// ShouldSkipHeavyFuzzing implements the mandate's "Smart Stealth Routing"
// decision: heavy injection fuzzing (XSS/SQLi/SSTI) is skipped on a
// WAF-protected endpoint UNLESS the operator explicitly asked for --waf-bypass.
//
//   - wafProtected: the host was fingerprinted as WAF-protected.
//   - wafBypass:    the value of the --waf-bypass flag.
//
// Returns true when the caller should SKIP heavy fuzzing for this host.
func ShouldSkipHeavyFuzzing(wafProtected, wafBypass bool) bool {
	return wafProtected && !wafBypass
}

// HeavyFuzzCategories are the injection classes gated by ShouldSkipHeavyFuzzing.
// Exposed so phases/tests can iterate a single authoritative list.
var HeavyFuzzCategories = []string{"XSS", "SQLi", "SSTI", "CommandInjection", "XXE"}

// FingerprintWAFResponse is a convenience over FingerprintWAF that lower-cases
// the body for the caller.
func FingerprintWAFResponse(status int, headers http.Header, body string) WAFFingerprint {
	return FingerprintWAF(status, headers, strings.ToLower(body))
}
