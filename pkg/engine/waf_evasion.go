// ─────────────────────────────────────────────────────────────────────────
// V9.0 ABSOLUTE APEX — Section 1.2: WAF & CDN Evasion Engine.
//
// This module fingerprints the major WAF/CDN products from response headers
// and body signals, and provides the "smart stealth routing" decision the
// orchestrator uses to skip heavy fuzzing (XSS/SQLi/SSTI) on WAF-protected
// endpoints unless the operator passed --waf-bypass.
//
// It is intentionally pure (no network I/O of its own): callers pass in an
// already-captured status/header/body triple. This keeps the classifier
// deterministic and unit-testable, and lets both the HTTP-probe phase and the
// exploit engines share one authoritative WAF verdict.
// ─────────────────────────────────────────────────────────────────────────

// WAFVendor identifies a detected WAF/CDN product.
type WAFVendor string

const (
	WAFNone       WAFVendor = ""
	WAFCloudflare WAFVendor = "Cloudflare"
	WAFAkamai     WAFVendor = "Akamai"
	WAFImperva    WAFVendor = "Imperva/Incapsula"
	WAFAWS        WAFVendor = "AWS WAF"
	WAFSucuri     WAFVendor = "Sucuri"
	WAFF5         WAFVendor = "F5 BIG-IP ASM"
	WAFFastly     WAFVendor = "Fastly"
	WAFGeneric    WAFVendor = "Generic WAF"
)

// WAFFingerprint is the verdict of classifying a single response.
type WAFFingerprint struct {
	// Detected is true when any WAF/CDN gate signal was found.
	Detected bool
	// Vendor is the best-guess product (WAFNone when not detected).
	Vendor WAFVendor
	// Challenge is true when the response is an active challenge / block page
	// (JS challenge, CAPTCHA, 403 interstitial) rather than a passthrough CDN.
	Challenge bool
	// Signals lists the concrete evidence strings that matched (for the trail).
	Signals []string
}

// wafHeaderSignal maps a (header, lower-cased value substring) pair to a vendor.
// An empty valueSubstr matches on mere header presence.
type wafHeaderSignal struct {
	header     string
	valueSub   string
	vendor     WAFVendor
	isChalenge bool
}

