// ─────────────────────────────────────────────────────────────────────────────
// Gate 3 (exploitability) and Gate 4 (scope).
// ─────────────────────────────────────────────────────────────────────────────

func TestGate3_NotExploitableRejected(t *testing.T) {
	v := NewFPValidator(alwaysInScope)
	c := Candidate{
		Type:                   "idor",
		URL:                    "https://target.com/a?id=1",
		InScope:                true,
		RequiresExploitability: true,
		Exploitable:            false, // phase could not prove it
		SkipReproduce:          true,
	}
	verdict := v.Validate(context.Background(), c)
	if verdict.Passed || verdict.Gate != 3 {
		t.Fatalf("expected Gate-3 rejection for unproven exploit, got %+v", verdict)
	}
}

