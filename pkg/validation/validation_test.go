// ─────────────────────────────────────────────────────────────────────────────
// A clean, exploitable, in-scope, one-shot finding passes all gates.
// ─────────────────────────────────────────────────────────────────────────────

func TestValidCandidatePasses(t *testing.T) {
	v := NewFPValidator(alwaysInScope)
	c := Candidate{
		Type:                   "ssti",
		URL:                    "https://target.com/p?q=x",
		InScope:                true,
		RequiresExploitability: true,
		Exploitable:            true,
		SkipReproduce:          true, // exploit already confirmed by the phase
		Evidence:               "param q evaluated {{1337*1339}} → 1790243 appeared",
	}
	verdict := v.Validate(context.Background(), c)
	if !verdict.Passed {
		t.Fatalf("clean exploitable in-scope candidate should pass, got %+v", verdict)
	}
}

// ─────────────────────────────────────────────────────────────────────────────
// Gate 2 (private data): a "sensitive file" finding with no private-data
// signal in the evidence must be rejected as public content.
// ─────────────────────────────────────────────────────────────────────────────

func TestGate2_NoPrivateDataRejected(t *testing.T) {
	v := NewFPValidator(alwaysInScope)
	c := Candidate{
		Type:                "Config Exposure",
		URL:                 "https://target.com/robots.txt",
		InScope:             true,
		RequiresPrivateData: true,
		SkipReproduce:       true,
		Evidence:            "User-agent: * Disallow: /admin", // public, no secret
	}
	// needsBaseline is true for "exposure" types; with no reachable server the
	// baseline fetch errors and is skipped, so Gate 2 is the decisive gate.
	verdict := v.Validate(context.Background(), c)
	if verdict.Passed {
		t.Fatalf("public content must fail Gate 2 (no private data), got passed")
	}
}

func TestGate2_PrivateDataPasses(t *testing.T) {
	v := NewFPValidator(alwaysInScope)
	c := Candidate{
		Type:                "Secret Leak",
		URL:                 "https://target.com/x",
		InScope:             true,
		RequiresPrivateData: true,
		SkipReproduce:       true,
		Evidence:            `leaked aws_secret_access_key=AKIA... and db_password=hunter2`,
	}
	verdict := v.Validate(context.Background(), c)
	if !verdict.Passed {
		t.Fatalf("evidence containing real private-data signals should pass, got %+v", verdict)
	}
}

// ─────────────────────────────────────────────────────────────────────────────
// randomToken must produce distinct tokens (baseline probe relies on this).
// ─────────────────────────────────────────────────────────────────────────────

func TestRandomTokenDistinct(t *testing.T) {
	a := randomToken(20)
	b := randomToken(20)
	if a == "" || len(a) != 20 {
		t.Fatalf("randomToken length wrong: %q", a)
	}
	if a == b {
		t.Fatalf("randomToken should not repeat: %q == %q", a, b)
	}
}
