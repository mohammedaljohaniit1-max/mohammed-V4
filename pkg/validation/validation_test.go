// alwaysInScope is the scope oracle used by most tests.
func alwaysInScope(string) bool { return true }

// ─────────────────────────────────────────────────────────────────────────────
// Known-FP pre-gate: the exact V6 false positives must be rejected.
// ─────────────────────────────────────────────────────────────────────────────

func TestKnownFP_AWSALBCookieRejected(t *testing.T) {
	v := NewFPValidator(alwaysInScope)
	c := Candidate{
		Type:     "AWS Secret Key",
		URL:      "https://target.com/",
		InScope:  true,
		Evidence: "found Set-Cookie: AWSALB=abcdef0123456789; path=/",
	}
	verdict := v.Validate(context.Background(), c)
	if verdict.Passed {
		t.Fatalf("AWSALB cookie must be rejected as a known FP, got passed")
	}
}

